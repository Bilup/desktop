// desktop 依赖的是 Bilup/scratch-gui 的 **develop**（源码主线），而 develop 分支
// 不含 CI 生成的两个文件：
//
//   static/microbit/<version>.hex          micro:bit 固件本体
//   src/generated/microbit-hex-url.cjs     由上一个文件生成，导出它的 URL
//
// desktop 的编译闭包里有 scratch-gui 的 src/lib/microbit-update.js（经
// containers/connection-modal.jsx ← components/gui/gui.jsx），它写着
// `import hexUrl from '../generated/microbit-hex-url.cjs'`。缺这两个文件时
// webpack 会直接 Module not found，构建失败。
//
// 这里复刻 scratch-gui 自己的 scripts/prepublish.mjs（只做 hex 部分），
// 保持与网页端完全相同的来源与 SHA-256 校验，不引入新的第三方依赖
// （zip 解析复用 desktop 已有的 adm-zip）。
import fs from 'node:fs';
import pathUtil from 'node:path';
import crypto from 'node:crypto';

const ROOT = pathUtil.join(import.meta.dirname, '..');
const GUI_ROOT = pathUtil.join(ROOT, 'node_modules', 'scratch-gui');

// 与 scratch-gui/scripts/prepublish.mjs 保持一致
const HEX_ZIP_URL = 'https://packagerdata.turbowarp.org/scratch-microbit-1.2.0.hex.zip';
const EXPECTED_SHA256 = 'dfd574b709307fe76c44dbb6b0ac8942e7908f4d5c18359fae25fbda3c9f4399';

const main = async () => {
    if (!fs.existsSync(GUI_ROOT)) {
        console.log('[microbit] scratch-gui 未安装，跳过');
        return;
    }

    const hexDir = pathUtil.join(GUI_ROOT, 'static', 'microbit');
    const generatedDir = pathUtil.join(GUI_ROOT, 'src', 'generated');
    const generatedFile = pathUtil.join(generatedDir, 'microbit-hex-url.cjs');

    const existingHex = fs.existsSync(hexDir) &&
        fs.readdirSync(hexDir).find((name) => name.endsWith('.hex'));

    if (existingHex && fs.existsSync(generatedFile)) {
        console.log(`[microbit] 生成物已存在（static/microbit/${existingHex}），跳过`);
        return;
    }

    console.log(`[microbit] 下载 ${HEX_ZIP_URL}`);
    const response = await fetch(HEX_ZIP_URL);
    if (!response.ok) {
        throw new Error(`下载失败：HTTP ${response.status}`);
    }
    const zipBuffer = Buffer.from(await response.arrayBuffer());

    const sha256 = crypto.createHash('sha-256').update(zipBuffer).digest('hex');
    if (sha256 !== EXPECTED_SHA256) {
        throw new Error(`SHA-256 校验失败：得到 ${sha256}，期望 ${EXPECTED_SHA256}`);
    }

    // adm-zip 按需加载：本机未安装依赖时，"跳过"分支仍可正常运行
    const {default: AdmZip} = await import('adm-zip');
    const entry = new AdmZip(zipBuffer)
        .getEntries()
        .find((item) => {
            const baseName = pathUtil.basename(item.entryName);
            // zip 里除固件外还带 __MACOSX/._xxx.hex 资源分叉条目，必须排除
            return baseName.endsWith('.hex') &&
                !baseName.startsWith('._') &&
                !item.entryName.includes('__MACOSX');
        });
    if (!entry) {
        throw new Error('zip 内未找到 .hex 文件');
    }
    const hexFileName = pathUtil.basename(entry.entryName);

    fs.mkdirSync(hexDir, {recursive: true});
    fs.writeFileSync(pathUtil.join(hexDir, hexFileName), entry.getData());
    console.log(`[microbit] 写入 static/microbit/${hexFileName}`);

    fs.mkdirSync(generatedDir, {recursive: true});
    fs.writeFileSync(generatedFile, [
        '// This file is generated by scripts/prepare-microbit-hex.mjs',
        '// Do not edit this file directly',
        '// This file relies on a loader to turn this `require` into a URL',
        `module.exports = require('./../../static/microbit/${hexFileName}');`,
        '' // final newline
    ].join('\n'));
    console.log('[microbit] 写入 src/generated/microbit-hex-url.cjs');
};

main().catch((error) => {
    console.error(`[microbit] ${error.message}`);
    process.exit(1);
});
